#!/usr/bin/env python3
"""Optional maintainer utility. Users just open the committed standalone.html.
Small deterministic linker for this repository's static ES modules; no downloads.
"""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
FILES = ['iso-kit.mjs', 'lathe.mjs', 'gl.mjs', 'src/data.js', 'src/model.js',
         'src/webgl2/math.js', 'src/webgl2/geometry.js', 'src/webgl2/gpu.js',
         'src/webgl2/cloud.js', 'src/webgl2/world.js', 'src/expedition.js']
modules = ['"use strict";\nconst __modules = Object.create(null);']
for name in FILES:
    path = ROOT / name
    text = path.read_text()
    exports = re.findall(r'export\s+(?:const|let|var|function|class)\s+(\w+)', text)
    def replace_import(match):
        clause, relative = match.groups()
        target = (path.parent / relative).resolve().relative_to(ROOT).as_posix()
        if clause.startswith('* as '):
            return f'const {clause[5:].strip()} = __modules["{target}"];'
        if clause.startswith('{'):
            clause = re.sub(r'\b(\w+)\s+as\s+(\w+)', r'\1: \2', clause)
            return f'const {clause} = __modules["{target}"];'
        raise ValueError(f'Unsupported import: {clause}')
    text = re.sub(r'import\s+(.+?)\s+from\s+[\'"](.+?)[\'"];?', replace_import, text)
    text = re.sub(r'\bexport\s+(?=(const|let|var|function|class)\b)', '', text)
    modules.append(f'__modules["{name}"] = (() => {{\n{text}\nreturn {{{",".join(exports)}}};\n}})();')
script = '\n'.join(modules).replace('</script', '<\\/script')
html = (ROOT / 'index.html').read_text()
html = html.replace('<link rel="stylesheet" href="expedition.css">', '<style>\n'+(ROOT/'expedition.css').read_text()+'\n</style>')
html = html.replace('<script type="module" src="src/expedition.js"></script>', '<script>\n'+script+'\n</script>')
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by tools/make_standalone.py; edit src/, index.html and expedition.css instead. -->', 1)
html = html.replace('href="./" aria-label="Микрокосмос, главная"', 'href="#" aria-label="Микрокосмос, главная"')
(ROOT/'standalone.html').write_text(html)
print(f'standalone.html: {len(html.encode()):,} bytes, no runtime imports')
